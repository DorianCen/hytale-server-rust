// Ported from: `.hytale-source/.../worldgen/chunk/populator/PrefabPopulator.java`
//! Java `com.hypixel.hytale.server.worldgen.chunk.populator.PrefabPopulator`
//! — the *biome prefab* stage of
//! [`crate::chunk::ChunkGeneratorExecution::execute`].
//!
//! # The stage in one paragraph
//!
//! 1. **Collect the biomes**, the **candidates** and **invalidate** the
//!    overlapping ones — the shared placement pass of
//!    `crate::chunk::populator::prefab_placement_pass`, which runs against a
//!    `PlacementContext`. The populator's context is the chunk being
//!    generated (the `ChunkCtx` adapter); a later headless feature query
//!    runs the same pass against an arbitrary rectangle.
//! 2. **Generate** the surviving candidates: the prefab is pasted into the
//!    chunk with the `PREFAB` priority. The paste is the populator's own
//!    final phase — the shared pass never writes blocks.
//! 3. **Generate the unique prefabs** (the spawn points, the landmarks, …)
//!    — the entries come from the per-seed
//!    [`crate::chunk::chunk_generator::ChunkGenerator::generate_unique_prefabs`]
//!    list (the Java caches it in the `UniquePrefabCache`); every entry whose
//!    bounds overlap the chunk is pasted with the `PREFAB` priority.
//!
//! # Bit-exactness
//!
//! The populator is a **long random stream**: the collection consumes draws
//! from the shared [`FastRandom`](hytale_math::fast_random::FastRandom) and
//! the draws happen in the Java order. The exact order (the per-lattice-point
//! seed, the weighted pick, the rotation, the height/parent/base checks) is
//! documented and transcribed in `prefab_placement_pass`; this module must
//! not add, remove or reorder a draw in that path.
//!
//! # Deviations
//!
//! * **The unique prefabs are generated by the chunk generator** (Phase 5c)
//!   — the populator only *places* the entries of the per-seed list (the
//!   Java does the same: `execution.getChunkGenerator().getUniquePrefabs(seed)`).
//! * **The paste buffer is allocated per paste** — the Java reuses the
//!   thread-local `ChunkGeneratorResource.prefabBuffer`, but the Rust
//!   [`PrefabPasteBuffer`] borrows the execution mutably, so it cannot live
//!   in the (unborrowed) resource. The buffer is fully re-seeded before
//!   every paste, so the reuse is not observable.
//! * **The Java `getBenchmark()` timing hook is not ported** — per-stage
//!   timings live in `StageTimings` / `WorldGenStats` instead.
//! * **The collection state lives in the shared `PlacementCollector`** —
//!   see below; the populator owns it and does not read the candidates
//!   itself except in the paste phase.

