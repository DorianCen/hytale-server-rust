/// The [`PlacementContext`] of the populator: the chunk being generated.
///
/// The window is the chunk's block bounds, the core biomes are the biome of
/// every core-data entry, the region scan skips the chunk padded by the
/// interpolation radius (those columns come from the core data), and the
/// base check reads the height **through the execution** — see the trait
/// docs for why this must not become
/// [`ChunkGenerator::get_height`].
pub(crate) struct ChunkCtx<'a> {
    /// The execution of the chunk being generated.
    execution: &'a ChunkGeneratorExecution,
}

impl<'a> ChunkCtx<'a> {
    /// The context of the given execution.
    pub(crate) fn new(execution: &'a ChunkGeneratorExecution) -> Self {
        Self { execution }
    }
}

impl PlacementContext for ChunkCtx<'_> {
    fn window_min_x(&self) -> i32 {
        chunk_util::min_block(self.execution.get_x())
    }

    fn window_min_z(&self) -> i32 {
        chunk_util::min_block(self.execution.get_z())
    }

    fn window_max_x(&self) -> i32 {
        chunk_util::max_block(self.execution.get_x())
    }

    fn window_max_z(&self) -> i32 {
        chunk_util::max_block(self.execution.get_z())
    }

    fn generator(&self) -> &ChunkGenerator {
        self.execution.get_chunk_generator()
    }

    fn core_biomes(&self) -> Vec<Rc<dyn Biome>> {
        let mut biomes = Vec::new();
        for entry in self.execution.get_core_data_entries() {
            let Some(entry) = entry else {
                continue;
            };
            let biome = entry
                .zone_biome_result
                .read()
                .unwrap_or_else(|poisoned| poisoned.into_inner())
                .get_biome()
                .cloned();
            let Some(biome) = biome else {
                continue;
            };
            biomes.push(biome);
        }
        biomes
    }

    fn interior_skip_bounds(&self) -> Option<(i32, i32, i32, i32)> {
        Some((
            self.window_min_x() - crate::chunk::MAX_RADIUS,
            self.window_min_z() - crate::chunk::MAX_RADIUS,
            self.window_max_x() + crate::chunk::MAX_RADIUS,
            self.window_max_z() + crate::chunk::MAX_RADIUS,
        ))
    }

    fn base_check_height(&self, seed: i32, x: i32, z: i32) -> i32 {
        self.execution.get_height(seed, x, z)
    }
}
