/// Java `public class PrefabPopulator`.
///
/// The Java populator is a *stateful* object that lives in the thread-local
/// [`ChunkGeneratorResource`]; the Rust port keeps the same shape (the
/// collection state — biomes, candidates and invalidation bits — lives in the
/// shared `PlacementCollector`) so that the reuse semantics of the Java are
/// preserved.
pub struct PrefabPopulator {
    /// Java `private int worldSeed`, `prefabSeed`, `minPriority`, `random`,
    /// `biomes`, `prefabs` and `invalidated` — the collection state, shared
    /// with the future feature query.
    collector: PlacementCollector,
}

impl Default for PrefabPopulator {
    fn default() -> Self {
        Self::new()
    }
}

impl PrefabPopulator {
    /// Java `new PrefabPopulator()` — the implicit constructor of the Java
    /// class (the fields are the initialised ones).
    pub fn new() -> Self {
        Self {
            collector: PlacementCollector::new(),
        }
    }

    /// Java `public static void populate(int seed, @Nonnull
    /// ChunkGeneratorExecution execution)`.
    ///
    /// The Java method reaches the per-thread populator through
    /// `ChunkGenerator.getResource().prefabPopulator`; the Rust port takes
    /// the resource explicitly (the plan's "explicit `&mut` scratch per
    /// task" model).
    pub fn populate(
        seed: i32,
        execution: &mut ChunkGeneratorExecution,
        resource: &mut ChunkGeneratorResource,
    ) {
        resource.prefab_populator.run(seed, execution);
    }

    /// Java `public void run(int seed, @Nonnull ChunkGeneratorExecution
    /// execution)`.
    fn run(&mut self, seed: i32, execution: &mut ChunkGeneratorExecution) {
        self.collector.reset();
        self.collector.world_seed = seed;
        self.collector.min_priority = PrefabCategory::MAX_PRIORITY;

        // Java: `this.uniquePrefabs = Objects.requireNonNullElse(execution.getChunkGenerator().getUniquePrefabs(seed), EMPTY_UNIQUE_PREFABS);`
        let unique_prefabs = execution.get_chunk_generator().get_unique_prefabs(seed);

        {
            let ctx = ChunkCtx::new(execution);
            self.collector.collect_biomes(&ctx);
            self.collector.collect_prefabs(&ctx, &unique_prefabs);
        }
        self.collector.invalidate_prefabs();
        self.generate_prefabs(seed, execution);
        self.generate_unique_prefabs(seed, execution, &unique_prefabs);

        // Java: the tail of `run` resets the state.
        self.collector.reset();
    }

    /* ============================================================================================================ \\
    ||                                                                                                               ||
    ||                                               GENERATION                                                    ||
    ||                                                                                                               ||
    \\ ============================================================================================================ */

    /// Java `private void generatePrefabs(int seed, @Nonnull
    /// ChunkGeneratorExecution execution)`.
    fn generate_prefabs(&mut self, seed: i32, execution: &mut ChunkGeneratorExecution) {
        for i in 0..self.collector.candidates().len() {
            if self.collector.invalidated(i) {
                continue;
            }

            let candidate = &self.collector.candidates()[i];
            let x = candidate.x;
            let y = candidate.y;
            let z = candidate.z;
            let rotation = candidate.rotation;
            let supplier = Rc::clone(&candidate.supplier);

            let bounds = supplier.get_bounds();
            if !Self::is_matching_chunk_bounds(x, z, execution, rotation, &bounds) {
                continue;
            }

            let config = candidate.generator.get_prefab_placement_configuration();
            let height_condition = candidate.generator.get_height_condition();
            let environment = candidate.entry.get_environment_id();
            let fit_heightmap = candidate.generator.is_fit_heightmap();
            let submerge = candidate.generator.is_submerge();

            Self::generate_prefab_at(
                seed,
                x,
                z,
                y,
                execution,
                &supplier,
                config,
                rotation,
                height_condition,
                environment,
                fit_heightmap,
                submerge,
            );
        }
    }

    /// Java `private void generateUniquePrefabs(final int seed, @Nonnull final
    /// ChunkGeneratorExecution execution)`.
    fn generate_unique_prefabs(
        &mut self,
        seed: i32,
        execution: &mut ChunkGeneratorExecution,
        unique_prefabs: &[UniquePrefabEntry],
    ) {
        let default_true: Rc<dyn ICoordinateRndCondition> =
            Rc::new(DefaultCoordinateRndCondition::True);

        for entry in unique_prefabs {
            if !Self::is_matching_chunk_bounds_absolute(
                execution,
                entry.get_low_bound_x(),
                entry.get_low_bound_z(),
                entry.get_high_bound_x(),
                entry.get_high_bound_z(),
            ) {
                continue;
            }
            let position = entry.get_position();
            Self::generate_prefab_at(
                seed,
                position.0,
                position.2,
                position.1,
                execution,
                entry.get_prefab_supplier(),
                entry.get_configuration(),
                entry.get_rotation(),
                &default_true,
                entry.get_environment_id(),
                entry.is_fit_heightmap(),
                entry.is_submerge(),
            );
        }
    }

    /// Java `private static void generatePrefabAt(int seed, int x, int z, int
    /// height, @Nonnull ChunkGeneratorExecution execution, @Nonnull
    /// WorldGenPrefabSupplier supplier, BlockMaskCondition configuration,
    /// PrefabRotation rotation, ICoordinateRndCondition heightCondition, int
    /// environmentId, boolean fitHeightmap, boolean submerge)`.
    #[allow(clippy::too_many_arguments)]
    fn generate_prefab_at(
        seed: i32,
        x: i32,
        z: i32,
        height: i32,
        execution: &mut ChunkGeneratorExecution,
        supplier: &Rc<WorldGenPrefabSupplier>,
        configuration: &BlockMaskCondition,
        rotation: PrefabRotation,
        height_condition: &Rc<dyn ICoordinateRndCondition>,
        environment_id: i32,
        fit_heightmap: bool,
        submerge: bool,
    ) {
        let cx = x - chunk_util::min_block(execution.get_x());
        let cz = z - chunk_util::min_block(execution.get_z());
        let external_seed = hash_util::hash2(x as i64, z as i64).wrapping_mul(0xc0e3_94ca);

        // Deviation: the Java reuses the thread-local paste buffer; the Rust
        // buffer borrows the execution, so it is allocated per paste (the
        // buffer is fully re-seeded, so the reuse is not observable).
        let buffer = PrefabPasteBuffer::new();
        buffer.set_seed(seed, external_seed);
        *buffer.execution.borrow_mut() = Some(execution);
        *buffer.block_mask.borrow_mut() = Some(configuration.clone());
        buffer.environment_id.set(environment_id);
        buffer.fit_heightmap.set(fit_heightmap);
        buffer.priority.set(if submerge {
            worldgen_model::block_priority::PREFAB | worldgen_model::block_priority::FLAG_SUBMERGE
        } else {
            worldgen_model::block_priority::PREFAB
        });
        *buffer.spawn_condition.borrow_mut() = Rc::clone(height_condition);

        // Java: the benchmark block (`getBenchmark().registerPrefab`) is
        // Phase-6 timing collection and is not ported.

        let paste_supplier: Rc<dyn PrefabSupplier> = Rc::new(supplier.as_ref().clone());
        crate::prefab::prefab_paste_util::generate(
            &buffer,
            rotation,
            paste_supplier,
            x,
            height,
            z,
            cx,
            cz,
        );
    }

    /// Java `private static boolean isMatchingChunkBounds(int x, int z,
    /// @Nonnull ChunkGeneratorExecution execution, @Nonnull PrefabRotation
    /// rotation, @Nonnull IChunkBounds bounds)`.
    fn is_matching_chunk_bounds(
        x: i32,
        z: i32,
        execution: &ChunkGeneratorExecution,
        rotation: PrefabRotation,
        bounds: &dyn IChunkBounds,
    ) -> bool {
        let min_x = x.wrapping_add(bounds.get_low_bound_x_rotated(rotation));
        let min_z = z.wrapping_add(bounds.get_low_bound_z_rotated(rotation));
        let max_x = x.wrapping_add(bounds.get_high_bound_x_rotated(rotation));
        let max_z = z.wrapping_add(bounds.get_high_bound_z_rotated(rotation));
        Self::is_matching_chunk_bounds_absolute(execution, min_x, min_z, max_x, max_z)
    }

    /// Java `private static boolean isMatchingChunkBounds(@Nonnull
    /// ChunkGeneratorExecution execution, int lowBoundX, int lowBoundZ, int
    /// highBoundX, int highBoundZ)`.
    fn is_matching_chunk_bounds_absolute(
        execution: &ChunkGeneratorExecution,
        low_bound_x: i32,
        low_bound_z: i32,
        high_bound_x: i32,
        high_bound_z: i32,
    ) -> bool {
        chunk_util::max_block(execution.get_x()) >= low_bound_x
            && chunk_util::min_block(execution.get_x()) <= high_bound_x
            && chunk_util::max_block(execution.get_z()) >= low_bound_z
            && chunk_util::min_block(execution.get_z()) <= high_bound_z
    }
}

